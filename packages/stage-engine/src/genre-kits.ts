/**
 * ZERO-TOKEN DETERMINISTIC COMPILER:
 * Converts raw script text into a full sequence of ChoreographedStageScenes
 * using keyword heuristics, genre defaults, and alternating camera choreography.
 * Runs in <5 milliseconds with 0 API calls!
 */
export function compileScriptToDeterministicStageScenes(
  scriptText: string,
  genreKitId: VideoGenreKitId
): {
  readonly estimatedDurationSec: number;
  readonly scenes: readonly {
    readonly startTimeSec: number;
    readonly durationSec: number;
    readonly spokenLine: string;
    readonly stageScene: ChoreographedStageScene;
  }[];
} {
  const kit = GENRE_KIT_CATALOG[genreKitId];
  const sentences = scriptText
    .split(/(?<=[.!?;\n])\s+/)
    .map((s) => s.trim())
    .filter((s) => s.length > 0);

  const fallbackSentences =
    sentences.length > 0
      ? sentences
      : [
          'Tại sao nền kinh tế và vũ trụ lại vận hành theo những quy luật kỳ lạ như vậy?',
          'Hãy nhìn vào biểu đồ tăng trưởng đột biến này khi dòng tiền được bơm ra liên tục.',
          'Nhưng ngay sau đó, khủng hoảng bất ngờ ập đến khiến tất cả hoảng loạn!',
        ];

  let cursorSec = 0;
  const compiledScenes = fallbackSentences.map((line, idx) => {
    const wordCount = line.split(/\s+/).length;
    // Average speaking rate ~ 2.8 words/sec, clamped between 3.0s and 6.5s per visual beat
    const durationSec = Math.min(6.5, Math.max(3.0, Number((wordCount / 2.8).toFixed(1))));
    const startTimeSec = cursorSec;
    cursorSec = Number((cursorSec + durationSec).toFixed(1));

    const moveSet = inferMoveSetFromTranscriptLine(line);
    const cameraRig = kit.recommendedCameras[idx % kit.recommendedCameras.length];
    const backdrop = kit.availableBackdrops[idx % kit.availableBackdrops.length];
    const widgetKind = kit.availableWidgets[idx % kit.availableWidgets.length];

    const lower = line.toLowerCase();
    const isPanicOrCrash =
      lower.includes('khủng hoảng') ||
      lower.includes('sụp đổ') ||
      lower.includes('hoảng loạn') ||
      lower.includes('crash');
    const isMoneyPrint = lower.includes('in tiền') || lower.includes('lạm phát') || lower.includes('bơm tiền');

    const stageScene: ChoreographedStageScene = {
      sceneId: `stage_scene_${idx + 1}`,
      genreKit: genreKitId,
      backdrop,
      atmosphere: isMoneyPrint
        ? 'particles.falling-dollar-bills'
        : isPanicOrCrash
        ? 'particles.red-crash-sparks'
        : kit.defaultAtmosphere,
      cameraRig: isPanicOrCrash ? 'crash-zoom-actor-face' : cameraRig,
      actors: [
        {
          actorId: `actor_main_${idx}`,
          displayName: kit.nameVi.split(' ')[1] || 'Narrator',
          archetype: kit.defaultHeroArchetype,
          moveSet,
          expression: isPanicOrCrash ? 'panic-sweat' : 'happy-talk',
          prop: moveSet === 'point-at-chart-high' ? 'pointer-stick' : 'none',
          stageX: 0.28,
          stageY: 0.78,
          scale: 1.0,
          flipHorizontal: false,
          enterAnimation: idx === 0 ? 'pop-spring' : 'slide-left',
          speechBubbleText: line.length <= 65 ? line : `${line.slice(0, 62)}...`,
        },
      ],
      widgets: [
        {
          widgetId: `widget_${idx}`,
          kind: widgetKind,
          title: `Minh họa Phân cảnh #${idx + 1}`,
          primaryValueLabel: line.slice(0, 32),
          stageX: 0.68,
          stageY: 0.48,
          scale: 1.0,
          accentColorHex: isPanicOrCrash ? '#EF4444' : '#3B82F6',
        },
      ],
      headlineBanner: idx === 0 ? line.toUpperCase() : undefined,
      transitionOutId: idx % 2 === 0 ? 'capcut.whip-pan-blur' : 'gl.directionalwipe',
      sfxTriggers: [
        { atNormalizedProgress: 0.0, sfxId: 'sfx.whoosh-soft' },
        { atNormalizedProgress: 0.15, sfxId: 'sfx.pop-bubble-02' },
      ],
    };

    return {
      startTimeSec,
      durationSec,
      spokenLine: line,
      stageScene,
    };
  });

  return {
    estimatedDurationSec: cursorSec,
    scenes: compiledScenes,
  };
}

